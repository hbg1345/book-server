    public static ResultHandler document(String identifier, Snippet... snippets) {
        String operationId = identifier.split("--", 2)[0];
        Operation operation = OPERATIONS.get(operationId);
        if (operation == null) throw new IllegalArgumentException("Missing API description: " + operationId);
        return result -> {
            var details = MockMvcRestDocumentationWrapper.resourceDetails()
                    .tag(operation.tag()).summary(operation.summary()).description(operation.description());
            var all = new ArrayList<Snippet>(Arrays.asList(snippets));
            int status = result.getResponse().getStatus();
            String schema = Arrays.stream(operationId.split("-"))
                    .map(word -> Character.toUpperCase(word.charAt(0)) + word.substring(1))
                    .reduce("", String::concat);
            byte[] requestBody = result.getRequest().getContentAsByteArray();
            if (requestBody != null && requestBody.length > 0 && status < 400) {
                details.requestSchema(Schema.schema(schema + "Request"));
            }
            if (!result.getResponse().getContentAsString().isBlank()) {
                details.responseSchema(Schema.schema(status >= 400 ? "ProblemDetail" : schema + "Response"));
                if (status >= 400) {
                    all.add(responseFields(
                            fieldWithPath("type").type(JsonFieldType.STRING).optional().description("문제 유형"),
                            fieldWithPath("title").type(JsonFieldType.STRING).description("오류 제목"),
                            fieldWithPath("status").type(JsonFieldType.NUMBER).description("HTTP 상태 코드"),
                            fieldWithPath("detail").type(JsonFieldType.STRING).optional().description("오류 원인"),
                            fieldWithPath("instance").type(JsonFieldType.STRING).optional().description("오류가 발생한 요청 경로"),
                            subsectionWithPath("errors").type(JsonFieldType.OBJECT).optional().description("입력 필드별 검증 오류")));
                }
            }
            Object template = result.getRequest().getAttribute(RestDocumentationGenerator.ATTRIBUTE_NAME_URL_TEMPLATE);
            if (template instanceof String path) {
                var matcher = Pattern.compile("\\{([^}]+)}").matcher(path);
                var parameters = new ArrayList<org.springframework.restdocs.request.ParameterDescriptor>();
                while (matcher.find()) {
                    String name = matcher.group(1);
                    String label = switch (name) {
                        case "purchaseUuid" -> "주문 식별자(UUID)";
                        case "bookUuid" -> "도서 식별자(UUID)";
                        case "addressUuid" -> "배송지 식별자(UUID)";
                        default -> name;
                    };
                    parameters.add(parameterWithName(name).description(label));
                }
                if (!parameters.isEmpty()) all.add(pathParameters(parameters));
            }
            MockMvcRestDocumentationWrapper.document(identifier, details, all.toArray(Snippet[]::new)).handle(result);
        };
    }
